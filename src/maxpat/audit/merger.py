"""Override merger: transforms proposed audit overrides into production overrides.json.

Reads proposed-overrides.json (generated by the audit pipeline), recomputes
conflicts against the LIVE overrides.json at merge time, applies field-level
conflict resolution, and writes overrides.json back in its own style.

Q30 / I5:

* Conflicts are recomputed when :meth:`OverrideMerger.merge` runs, against the
  file as it is then (re-read, aliases resolved): a manual entry added after
  the audit is never overwritten -- the proposal becomes a conflict.
* The file keeps its order: top-level keys and existing ``objects`` keys stay
  where they are; new names go at the end of their domain group (a missing
  group is created in ``DOMAIN_ORDER`` position). Nothing is re-sorted.
* :meth:`OverrideMerger.write` reproduces the file's own ``ensure_ascii`` and
  trailing newline, writes atomically keeping the file's mode, does nothing
  on identical bytes, and raises :class:`OverridesChangedError` if the file
  changed since ``merge()`` read it.

Load safety (quick 261022-ud6 WP1, review CR-02). Since Q11 the loader
(``ObjectDatabase._apply_object_overrides``) raises on an ``objects`` key
with no base domain entry and on two keys that resolve to one canonical name
through aliases.json, so:

* :meth:`OverrideMerger.merge` never adds a proposal whose canonical name has
  no domain entry; it lands in :attr:`OverrideMerger.skipped` as
  ``NO_BASE_ENTRY`` (no inactive ``_note`` entry is written any more).
* New entries are keyed by the canonical name. When an alias and its
  canonical name (``t`` / ``trigger``) are both proposed, the canonical
  spelling wins (else the first alias in name order); the rest are skipped
  as ``DUPLICATE_OF <canonical>``.
* :meth:`OverrideMerger.write` rehearses a load of the merged dict (a
  scratch DB root whose other files link to the real ones) and raises
  :class:`OverridesLoadError` without writing when ``ObjectDatabase`` would
  reject it.
"""

from __future__ import annotations

import copy
import json
import shutil
import tempfile
from pathlib import Path

from src.maxpat.atomic_io import atomic_write_bytes, json_style
from src.maxpat.db_lookup import ObjectDatabase

# Domain ordering for grouping in overrides.json
DOMAIN_ORDER = ["max", "msp", "jitter", "mc", "gen", "m4l", "rnbo", "packages", "other"]

# Canonical display labels for domain header comments
_DOMAIN_LABELS = {
    "max": "Max Objects",
    "msp": "MSP Objects",
    "jitter": "Jitter Objects",
    "mc": "MC Objects",
    "gen": "Gen Objects",
    "m4l": "Max for Live Objects",
    "rnbo": "RNBO Objects",
    "packages": "Package Objects",
    "other": "Other Objects (not in domain JSONs)",
}


CONFLICT_WITH_MANUAL = "CONFLICT_WITH_MANUAL"


class OverridesChangedError(Exception):
    """overrides.json changed on disk since merge() read it; write() refuses (Q30 PD-8)."""


class OverridesLoadError(ValueError):
    """The merged dict would make ``ObjectDatabase()`` raise; write() refuses (CR-02)."""


NO_BASE_ENTRY = "NO_BASE_ENTRY"
DUPLICATE_OF = "DUPLICATE_OF"


def _rehearsal_root(overrides_path: Path, db: ObjectDatabase) -> Path | None:
    """The DB root a rehearsal load mirrors: the overrides file's own
    directory when it is a DB root (holds aliases.json), else the root *db*
    was loaded from; None when neither is known."""
    parent = Path(overrides_path).parent
    if (parent / "aliases.json").is_file():
        return parent
    root = getattr(db, "db_root", None)
    return Path(root) if root is not None else None


def rehearse_load(merged: dict, db_root: Path) -> None:
    """Load ``ObjectDatabase`` from a scratch copy of *db_root* whose
    overrides.json is *merged*. Raises :class:`OverridesLoadError` naming
    the loader's message when it rejects the dict. Every other entry of the
    root is symlinked (copied where symlinks are unavailable)."""
    with tempfile.TemporaryDirectory(prefix="overrides-rehearsal-") as tmp:
        scratch = Path(tmp)
        for entry in Path(db_root).iterdir():
            if entry.name == "overrides.json":
                continue
            target = scratch / entry.name
            try:
                target.symlink_to(entry, target_is_directory=entry.is_dir())
            except OSError:
                if entry.is_dir():
                    shutil.copytree(entry, target)
                else:
                    shutil.copy2(entry, target)
        (scratch / "overrides.json").write_text(json.dumps(merged, indent=2))
        try:
            ObjectDatabase(scratch)
        except ValueError as exc:
            raise OverridesLoadError(
                f"merged overrides.json would not load: {exc}"
            ) from exc


class OverrideMerger:
    """Merges proposed audit overrides into the production overrides.json.

    Handles: merge-time conflict detection and field-level resolution, manual
    entry preservation, audit metadata, and placing new entries in their
    domain group without reordering anything that is already there.
    Idempotent -- running twice with the same inputs produces the same result.
    """

    def __init__(
        self,
        proposed_path: Path,
        overrides_path: Path,
        db: ObjectDatabase,
    ) -> None:
        """Initialize with paths to proposed and existing overrides files.

        Args:
            proposed_path: Path to proposed-overrides.json (audit output).
            overrides_path: Path to existing overrides.json (production file).
            db: ObjectDatabase instance for domain lookups.
        """
        self._proposed = json.loads(proposed_path.read_text())
        self._overrides_path = Path(overrides_path)
        self._db = db
        self._raw: bytes = b""
        self._existing: dict = {}
        # Proposal name -> reason, for proposals the last merge() did not add
        # (NO_BASE_ENTRY, "DUPLICATE_OF <canonical>"); conflicts are separate.
        self.skipped: dict[str, str] = {}
        self._read_live()

    def _read_live(self) -> None:
        """(Re-)read overrides.json, keeping its raw bytes for the stale guard."""
        self._raw = self._overrides_path.read_bytes()
        self._existing = json.loads(self._raw)

    def _canonical(self, name: str) -> str:
        aliases = getattr(self._db, "_aliases", None)
        if isinstance(aliases, dict):
            return aliases.get(name, name)
        return name

    def _live_entry_for(self, name: str) -> tuple[str, dict] | None:
        """The live manual entry for `name` (compared through the DB's aliases)."""
        live = self._existing.get("objects", {})
        if name in live and not name.startswith("_"):
            return name, live[name]
        target = self._canonical(name)
        for key, entry in live.items():
            if key.startswith("_") or not isinstance(entry, dict):
                continue
            if key == target or self._canonical(key) == target:
                return key, entry
        return None

    def _proposals(self) -> dict[str, dict]:
        """Every proposal in the proposal file: `objects` plus conflict audit sides."""
        proposals: dict[str, dict] = {}
        for name, entry in self._proposed.get("objects", {}).items():
            proposals[name] = entry
        for name, conflict in self._proposed.get("conflicts", {}).items():
            proposals.setdefault(name, conflict.get("audit_proposed", {}))
        return proposals

    def _compute_conflicts(self) -> dict[str, dict]:
        conflicts: dict[str, dict] = {}
        for name, entry in self._proposals().items():
            live = self._live_entry_for(name)
            if live is None:
                continue
            conflicts[name] = {
                "audit_proposed": copy.deepcopy(entry),
                "existing_manual": copy.deepcopy(live[1]),
                "reason": CONFLICT_WITH_MANUAL,
            }
        return conflicts

    def pending_variable_io_rules(self) -> dict[str, dict]:
        """The proposal file's ``variable_io_rules`` proposals: manual review only, never merged."""
        return dict(self._proposed.get("variable_io_rules") or {})

    def detect_conflicts(self) -> dict[str, dict]:
        """Conflicts recomputed against the live overrides.json (Q30 PD-8).

        A proposal (from the proposal file's ``objects`` or ``conflicts``) is
        a conflict iff the live file holds a manual entry for its name,
        compared through the DB's aliases. Each conflict has audit_proposed,
        existing_manual (the live entry) and reason keys.

        Returns:
            Dict mapping object name to conflict info. Empty dict if no conflicts.
        """
        self._read_live()
        return self._compute_conflicts()

    def merge(self, conflict_resolutions: dict | None = None) -> dict:
        """Execute the merge and return the new overrides dict.

        Re-reads overrides.json and recomputes conflicts against it (Q30
        PD-8): a proposal whose name has a live manual entry is a conflict
        and lands only through ``conflict_resolutions`` (replaced in place).
        Every other proposal is added, under its canonical name, at the end
        of its domain group; nothing already in the file moves. A proposal
        with no base domain entry, or a second spelling of one canonical
        name, is not added and is reported in :attr:`skipped` (CR-02).
        version_map, variable_io_rules and every other top-level section are
        preserved unchanged.

        Args:
            conflict_resolutions: Dict mapping object name to resolution
                instructions. Each value is a dict with "adopt_fields" key
                listing fields to take from the audit side. Fields not listed
                are preserved from the manual entry. None or missing entries
                mean the conflict is not resolved (existing manual entry is
                kept as-is).

        Returns:
            The complete merged overrides dict ready for writing.
        """
        if conflict_resolutions is None:
            conflict_resolutions = {}

        self._read_live()
        conflicts = self._compute_conflicts()
        merged = copy.deepcopy(self._existing)
        objects: dict = copy.deepcopy(self._existing.get("objects", {}))

        # CR-02: key new entries by canonical name and never add one the Q11
        # loader rejects (no base domain entry / alias + canonical twice).
        self.skipped = {}
        proposals = self._proposals()
        chosen: dict[str, str] = {}  # canonical -> proposal name
        for name in sorted(proposals):
            if name in conflicts:
                continue
            canonical = self._canonical(name)
            if not self._db.exists(canonical):
                self.skipped[name] = NO_BASE_ENTRY
                continue
            previous = chosen.get(canonical)
            if previous is None:
                chosen[canonical] = name
            elif name == canonical:
                self.skipped[previous] = f"{DUPLICATE_OF} {canonical}"
                chosen[canonical] = name
            else:
                self.skipped[name] = f"{DUPLICATE_OF} {canonical}"
        new_entries: dict[str, dict] = {
            canonical: copy.deepcopy(proposals[name])
            for canonical, name in chosen.items()
        }

        # Conflicts land only through conflict_resolutions, replaced in place.
        for name, conflict in conflicts.items():
            if name not in conflict_resolutions:
                continue  # unresolved: the manual entry stays as it is
            key, manual = self._live_entry_for(name)
            adopt_fields = conflict_resolutions[name].get("adopt_fields", [])
            audit_entry = conflict["audit_proposed"]
            resolved = copy.deepcopy(manual)
            resolved["_manual_original"] = copy.deepcopy(manual)
            for field in adopt_fields:
                if field in audit_entry:
                    resolved[field] = copy.deepcopy(audit_entry[field])
            if "_audit" in audit_entry:
                resolved["_audit"] = copy.deepcopy(audit_entry["_audit"])
            objects[key] = resolved

        merged["objects"] = self._place_new_entries(objects, new_entries)
        return merged

    def write(self, merged: dict) -> bool:
        """Write the merged overrides dict to disk in the file's own style.

        indent=2 with the file's own ensure_ascii and trailing newline (from
        ``json_style``; when the file is not reproducible: ensure_ascii True,
        trailing newline iff the file ends with one). The replace is atomic
        and keeps the file's mode.

        Args:
            merged: The complete merged overrides dict.

        Returns:
            False (nothing written) when the bytes would be identical.

        Raises:
            OverridesChangedError: the file changed since the last merge()
                read it (nothing written).
            OverridesLoadError: ``ObjectDatabase`` would reject *merged*
                (rehearsal load against a scratch DB root; nothing written).
        """
        current = self._overrides_path.read_bytes()
        if current != self._raw:
            raise OverridesChangedError(
                f"{self._overrides_path} changed on disk since merge() read it; "
                "re-run the merge"
            )
        root = _rehearsal_root(self._overrides_path, self._db)
        if root is not None:
            rehearse_load(merged, root)
        style = json_style(current, json.loads(current))
        if style is None:
            ensure_ascii, trailing_newline = True, current.endswith(b"\n")
        else:
            ensure_ascii, trailing_newline = style
        payload = (
            json.dumps(merged, indent=2, ensure_ascii=ensure_ascii)
            + ("\n" if trailing_newline else "")
        ).encode("utf-8")
        if payload == current:
            return False
        atomic_write_bytes(self._overrides_path, payload)
        self._raw = payload
        return True

    def _get_domain(self, obj_name: str) -> str:
        """Get the domain string for an object.

        Uses db.lookup() to find the domain. Falls back to 'other' if the
        object is not in any domain JSON.

        Args:
            obj_name: Object name to look up.

        Returns:
            Domain string (e.g., 'msp', 'max', 'jitter', 'other').
        """
        obj = self._db.lookup(obj_name)
        if obj is None:
            return "other"

        domain = obj.get("domain", obj.get("module", ""))
        if not domain:
            return "other"

        # Normalize domain names to lowercase short forms
        domain_lower = domain.lower()

        # Map known full names to short forms
        domain_map = {
            "max": "max",
            "msp": "msp",
            "jitter": "jitter",
            "mc": "mc",
            "gen": "gen",
            "m4l": "m4l",
            "rnbo": "rnbo",
            "packages": "packages",
        }

        for key, value in domain_map.items():
            if key in domain_lower:
                return value

        return "other"

    def _place_new_entries(self, objects: dict, new_entries: dict[str, dict]) -> dict:
        """Insert new entries without moving anything already there (Q30 PD-8).

        Every existing key (``_domain_*`` separators included) keeps its
        position. New names go at the end of their domain group -- just
        before the next ``_domain_*`` key, or at the end -- in name order. A
        missing group gets its ``_domain_<d>`` separator before the first
        existing separator that comes later in DOMAIN_ORDER (or at the end).

        Args:
            objects: The live ``objects`` section (conflict resolutions applied).
            new_entries: New object name -> entry.

        Returns:
            The ordered ``objects`` dict.
        """
        by_domain: dict[str, dict[str, dict]] = {}
        for name in sorted(new_entries):
            domain = self._get_domain(name)
            if domain not in DOMAIN_ORDER:
                domain = "other"
            by_domain.setdefault(domain, {})[name] = new_entries[name]

        items = list(objects.items())
        for domain in DOMAIN_ORDER:
            entries = by_domain.get(domain)
            if not entries:
                continue
            separator = f"_domain_{domain}"
            keys = [k for k, _ in items]
            if separator in keys:
                pos = keys.index(separator) + 1
                while pos < len(keys) and not keys[pos].startswith("_domain_"):
                    pos += 1
                block = list(entries.items())
            else:
                later = DOMAIN_ORDER[DOMAIN_ORDER.index(domain) + 1 :]
                pos = next(
                    (i for i, k in enumerate(keys) if k.startswith("_domain_") and k[len("_domain_"):] in later),
                    len(keys),
                )
                label = _DOMAIN_LABELS.get(domain, f"{domain.upper()} Objects")
                block = [(separator, f"--- {label} ---"), *entries.items()]
            items[pos:pos] = block
        return dict(items)
